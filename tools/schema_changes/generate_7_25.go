//go:build ignore

// Generate provider metadata from the pinned official 7.25 reference snapshot.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
)

type field struct {
	Wire               string   `json:"wire"`
	Kind               string   `json:"type"`
	ReadOnly           bool     `json:"readonly"`
	Required           bool     `json:"required"`
	Sensitive          bool     `json:"sensitive"`
	Enum               []string `json:"enum"`
	NumericAlternative bool     `json:"numeric_alternative"`
}

func main() {
	input := flag.String("input", "routeros-7.25-api.json", "Pinned official reference snapshot")
	output := flag.String("output", "routeros_7_25_catalog.go", "Generated Go file")
	flag.Parse()
	var manifest struct {
		Version       string `json:"version"`
		TargetVersion string `json:"target_version"`
		Menus         map[string]struct {
			Fields []field `json:"fields"`
		} `json:"menus"`
		Delta struct {
			Changes []struct {
				Path  string `json:"path"`
				Added struct {
					Params []string `json:"params"`
				} `json:"added"`
			} `json:"changedCommands"`
		} `json:"delta"`
	}
	data, err := os.ReadFile(*input)
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(data, &manifest); err != nil {
		log.Fatal(err)
	}
	if manifest.Version != "7.25" || manifest.TargetVersion != "7.25.1" || len(manifest.Menus) == 0 {
		log.Fatal("expected a non-empty RouterOS 7.25 reference targeting 7.25.1")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by tools/schema_changes/generate_7_25.go; DO NOT EDIT.\npackage routeros")
	fmt.Fprintf(&out, "const routerOS725MinimumVersion = %q\n\n", manifest.TargetVersion)
	fmt.Fprintln(&out, "var routerOS725Reference = map[string][]api725Field{")
	paths := make([]string, 0, len(manifest.Menus))
	for path := range manifest.Menus {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&out, "%q: {\n", "/"+path)
		for _, f := range manifest.Menus[path].Fields {
			fmt.Fprintf(&out, "{Wire:%q,Kind:%q,ReadOnly:%v,Required:%v,Sensitive:%v,Enum:[]string{", f.Wire, f.Kind, f.ReadOnly, f.Required, f.Sensitive)
			for _, value := range f.Enum {
				fmt.Fprintf(&out, "%q,", value)
			}
			fmt.Fprint(&out, "}")
			if f.NumericAlternative {
				fmt.Fprint(&out, ",NumericAlternative:true")
			}
			fmt.Fprintln(&out, "},")
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}\nvar routerOS725Additions = map[string][]string{")
	sort.Slice(manifest.Delta.Changes, func(i, j int) bool { return manifest.Delta.Changes[i].Path < manifest.Delta.Changes[j].Path })
	for _, change := range manifest.Delta.Changes {
		fmt.Fprintf(&out, "%q: {", "/"+change.Path)
		for _, param := range change.Added.Params {
			fmt.Fprintf(&out, "%q,", param)
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*output, formatted, 0644); err != nil {
		log.Fatal(err)
	}
}
