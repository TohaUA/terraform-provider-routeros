package main

import (
	"log"
	"os"
	"slices"
	"text/template"

	"gopkg.in/yaml.v3"
)

type driftAttrYAML struct {
	TF string
	MT string
}

type driftEntryYAML struct {
	Path  string
	Attrs []driftAttrYAML
}

func main() {
	fileOut, err := os.OpenFile("mikrotik_resource_drift.go", os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0644)
	if err != nil {
		log.Fatal(err)
	}
	defer fileOut.Close()

	m := map[string][]driftAttrYAML{}
	fileIn, err := os.Open("mikrotik_resource_drift.yaml")
	if err != nil {
		log.Fatalf("error: %v", err)
	}
	defer fileIn.Close()

	dec := yaml.NewDecoder(fileIn)
	if err := dec.Decode(&m); err != nil {
		log.Fatalf("error: %v", err)
	}

	paths := make([]string, 0, len(m))
	for path := range m {
		paths = append(paths, path)
	}
	slices.Sort(paths)

	entries := make([]driftEntryYAML, 0, len(paths))
	for _, path := range paths {
		entries = append(entries, driftEntryYAML{Path: path, Attrs: m[path]})
	}

	if err := driftTemplate.Execute(fileOut, entries); err != nil {
		log.Fatal(err)
	}
}

var driftTemplate = template.Must(template.New("").Parse(`// Code generated by "tools/drift/main.go"; DO NOT EDIT.
package routeros

func init() {
{{- range $entry := . }}
  {{- range $attr := $entry.Attrs }}
	{{ printf "driftAttributeSlice.Add(%q, %q, %q)" $entry.Path $attr.TF $attr.MT }}
  {{- end }}
{{- end }}
}
`))
